/**
 * The request behind "Запит для ChatGPT" on the add screen: send it with a
 * photo or text of a recipe, and the answer is text that parseRecipeText
 * reads without guessing. domain.test.ts parses RECIPE_FORMAT_EXAMPLE, and
 * docs/chatgpt-recipe-prompt.md repeats CHATGPT_PROMPT_TEMPLATE word for
 * word, so keep the three in step.
 */
export const RECIPE_FORMAT_EXAMPLE = [
  "Сирники зі сметаною",
  "Ніжні всередині, з рум’яною скоринкою.",
  "Порцій: 3",
  "Час: 25 хв",
  "Теги: Сніданок, Українська кухня, Вегетаріанське",
  "",
  "Інгредієнти:",
  "- Кисломолочний сир — 500 г",
  "- Яйце — 1 шт",
  "- Цукор — 2 ст. л.",
  "- Борошно — 4 ст. л.",
  "- Цибуля — 1 шт (дрібно нарізана)",
  "- Сіль (за смаком)",
  "- Сметана (для подачі)",
  "",
  "Приготування:",
  "1. Розімніть сир виделкою, додайте яйце, цукор і сіль.",
  "2. Сформуйте сирники і обваляйте в борошні.",
  "3. Смажте по 3 хвилини з кожного боку.",
].join("\n");

/** Replaced with the tags the app already uses when the request is copied. */
export const TAGS_PLACEHOLDER = "[теги з застосунку]";

export const CHATGPT_PROMPT_TEMPLATE = `Перепиши рецепт з фото або тексту, який я надішлю, точно у формат нижче, українською мовою. Поверни лише сам рецепт одним блоком тексту, без пояснень і без Markdown (без зірочок, решіток і жирного шрифту).

Формат:

${RECIPE_FORMAT_EXAMPLE}

Правила:
1. Перший рядок: назва страви. Далі, за бажанням, короткий опис в одному реченні.
2. Рядки «Порцій: число» і «Час: число хв» (загальний час приготування). Якщо в джерелі цього немає, пропусти рядок.
3. Рядок «Теги:» з 1 до 5 тегами через кому: тип страви, прийом їжі, кухня, особливості. Бери теги з цього списку: ${TAGS_PLACEHOLDER}. Новий тег додавай, лише якщо жоден зі списку не підходить; пиши його коротко, з великої літери, як у списку.
4. Заголовки «Інгредієнти:» і «Приготування:» пиши саме так, кожен в окремому рядку.
5. Один інгредієнт в рядку: назва в називному відмінку, потім « — », число і одиниця.
6. Одиниці лише такі: г, кг, мл, л, шт, ст. л., ч. л., склянка, зубч., пучок, щіпка, банка, уп.
7. Кількість цифрами: 200, 1,5 або дроби ½, ¼, ¾, ⅓, ⅔. Для діапазону пиши одне число.
8. Якщо кількості немає, пиши в дужках: (за смаком), (для подачі) або (за бажанням).
9. Уточнення до інгредієнта пиши в дужках у кінці рядка, наприклад: Цибуля — 1 шт (дрібно нарізана).
10. Один крок в рядку, з номером. Час у кроці пиши цифрами, наприклад «10 хвилин» або «1,5 години», щоб застосунок створив таймер.
11. Не додавай посилань, приміток від себе і нічого, чого немає в джерелі (крім тегів).`;

/** The request with the app's tags; a starter list while there are none. */
export const chatgptPrompt = (knownTags: string[]): string =>
  CHATGPT_PROMPT_TEMPLATE.replace(
    TAGS_PLACEHOLDER,
    knownTags.length
      ? knownTags.join(", ")
      : "Сніданок, Обід, Вечеря, Суп, Салат, Основна страва, Десерт, Випічка, Українська кухня, Вегетаріанське"
  );
