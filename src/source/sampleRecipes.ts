export interface ISampleData {
  recipes: IRecipe[];
  photos: Record<string, string>;
  shopping: IShoppingItem[];
}

export const buildSampleData = (now = Date.now()): ISampleData => {
  const iso = (daysAgo: number) =>
    new Date(now - daysAgo * DAY_MS).toISOString();
  const photos: Record<string, string> = {};

  const recipes = SAMPLES.map((s): IRecipe => {
    const photoId = s.photo ? `sample-${s.id}` : null;
    if (s.photo && photoId) photos[photoId] = samplePhoto(s.photo);
    return {
      id: s.id,
      title: s.title,
      description: s.description,
      photoId,
      tags: s.tags,
      totalMin: s.totalMin,
      servings: s.servings,
      ingredients: parseIngredients(s.ing.join("\n")),
      steps: parseSteps(s.steps.join("\n")),
      notes: "",
      favorite: Boolean(s.favorite),
      cookCount: s.cooked,
      lastCookedAt: iso(s.lastCooked),
      createdAt: iso(s.created),
      updatedAt: iso(s.created),
    };
  });

  const shopping: IShoppingItem[] = [];
  const add = (
    recipe: IRecipe | null,
    name: string,
    qty: number | null,
    unit: string,
    checked = false
  ) =>
    shopping.push({
      id: `sample-${shopping.length}`,
      name,
      qty,
      unit,
      recipeId: recipe?.id ?? null,
      recipeTitle: recipe?.title ?? null,
      checked,
      addedAt: iso(0),
    });
  const [borshch, , , , , banosh] = recipes;
  add(borshch, "Буряк", 2, "шт");
  add(borshch, "Капуста білокачанна", 300, "г");
  add(borshch, "Квасоля консервована", 1, "банка", true);
  add(borshch, "Сметана", null, "");
  add(banosh, "Сметана", 400, "г");
  add(banosh, "Бринза", 150, "г");
  add(null, "Хліб житній", 1, "шт");
  add(null, "Кава мелена", null, "", true);

  return { recipes, photos, shopping };
};
